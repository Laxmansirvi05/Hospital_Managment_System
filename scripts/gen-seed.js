// Writes supabase/seed.sql from server/db/seed-data.js, so the memory store and the database
// hold the same sample listings. Run: node scripts/gen-seed.js
import { writeFile } from 'node:fs/promises';
import { HOSPITALS, DOCTORS, PHARMACIES, DIAGNOSTICS, MEDICINES } from '../server/db/seed-data.js';

const lit = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return `array[${v.map(lit).join(', ')}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const point = (x) => `extensions.st_setsrid(extensions.st_makepoint(${x.lng}, ${x.lat}), 4326)::extensions.geography`;
const row = (vals) => `  (${vals.join(', ')})`;

const out = ['-- Generated by scripts/gen-seed.js. Synthetic sample listings only. Do not edit by hand.', 'begin;', ''];

out.push('insert into public.hospitals (id, name, area, address, location, description, phone, email, website, emergency_available, specialities, departments, rating, rating_count, source_platform, source_url, checked_at) values');
out.push(HOSPITALS.map((h) => row([lit(h.id), lit(h.name), lit(h.area), lit(h.address), point(h), lit(h.description), lit(h.phone), lit(h.email), lit(h.website), lit(h.emergencyAvailable), lit(h.specialities), lit(h.departments), lit(h.rating), lit(h.ratingCount), lit(h.sourcePlatform), lit(h.sourceUrl), lit(h.checkedAt)])).join(',\n'));
out.push('on conflict (id) do nothing;', '');

out.push('insert into public.doctors (id, name, specialization, qualifications, experience_years, hospital_id, clinic_name, clinic_area, clinic_address, clinic_phone, clinic_location, published_timings, profile_url, rating, rating_count, source_platform, source_url, checked_at) values');
out.push(DOCTORS.map((d) => row([lit(d.id), lit(d.name), lit(d.specialization), lit(d.qualifications), lit(d.experienceYears), lit(d.hospitalId), lit(d.clinicName ?? null), lit(d.area ?? null), lit(d.clinicAddress ?? null), lit(d.clinicPhone ?? null), d.hospitalId ? 'null' : point(d), lit(d.publishedTimings), lit(d.profileUrl), lit(d.rating), lit(d.ratingCount), lit(d.sourcePlatform), lit(d.sourceUrl), lit(d.checkedAt)])).join(',\n'));
out.push('on conflict (id) do nothing;', '');

out.push('insert into public.pharmacies (id, name, area, address, location, phone, email, website, hours, open_24, rating, rating_count, source_platform, source_url, checked_at) values');
out.push(PHARMACIES.map((p) => row([lit(p.id), lit(p.name), lit(p.area), lit(p.address), point(p), lit(p.phone), lit(p.email), lit(p.website), lit(p.hours), lit(p.open24), lit(p.rating), lit(p.ratingCount), lit(p.sourcePlatform), lit(p.sourceUrl), lit(p.checkedAt)])).join(',\n'));
out.push('on conflict (id) do nothing;', '');

out.push('insert into public.diagnostic_centres (id, name, area, address, location, description, phone, email, website, hours, tests_listed, rating, rating_count, source_platform, source_url, checked_at) values');
out.push(DIAGNOSTICS.map((c) => row([lit(c.id), lit(c.name), lit(c.area), lit(c.address), point(c), lit(c.description), lit(c.phone), lit(c.email), lit(c.website), lit(c.hours), lit(c.testsListed), lit(c.rating), lit(c.ratingCount), lit(c.sourcePlatform), lit(c.sourceUrl), lit(c.checkedAt)])).join(',\n'));
out.push('on conflict (id) do nothing;', '');

out.push('insert into public.medicines (id, name, form, pack, prescription_required) values');
out.push(MEDICINES.map((m) => row([lit(m.id), lit(m.name), lit(m.form), lit(m.pack), lit(m.prescriptionRequired)])).join(',\n'));
out.push('on conflict (id) do nothing;', '');

out.push('insert into public.medicine_listings (medicine_id, platform, price_inr, product_url, checked_at) values');
out.push(MEDICINES.flatMap((m) => m.listings.map((l) => row([lit(m.id), lit(l.platform), lit(l.priceInr), lit(l.productUrl), lit(l.checkedAt)]))).join(',\n'));
out.push('on conflict (medicine_id, platform) do nothing;', '', 'commit;', '');

await writeFile(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log('Wrote supabase/seed.sql');
